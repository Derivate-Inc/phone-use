import { REGISTRY } from './registry.ts';

// ---------------------------------------------------------------------------
// `phone-use completion <shell>` — static completion scripts generated from
// the live REGISTRY, so new verbs and flags appear without touching this
// file. Install lines (printed by the command's --help in index.ts):
//   zsh:  phone-use completion zsh  > ~/.zsh/completions/_phone-use
//   bash: phone-use completion bash > ~/.bash_completion.d/phone-use
//   fish: phone-use completion fish > ~/.config/fish/completions/phone-use.fish
// ---------------------------------------------------------------------------

export const COMPLETION_SHELLS = ['zsh', 'bash', 'fish'] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

// Non-verb commands and their completable flags.
const STATIC_COMMANDS: [name: string, desc: string, flags: string[]][] = [
  ['mcp', 'MCP server on stdio', ['--device']],
  ['task', 'one-off natural-language goal', ['--device', '--json', '--expect']],
  ['run', 'verified mobile workflow', ['--device', '--platform', '--output', '--yes', '--json']],
  ['compare', 'compare mobile harnesses', ['--output']],
  ['bench', 'self-verifying benchmark', ['--format', '--json', '--output']],
  ['doctor', 'environment diagnostics', ['--json']],
  ['sim', 'simulator logs, recording, permissions, push', ['--path']],
  ['export', 'export atlas bundle', []],
  ['inspect', 'preview an atlas bundle', []],
  ['import', 'import an atlas bundle', []],
  ['completion', 'print a shell completion script', []],
];

const VERB_FLAGS = ['--yes', '--json', '--help'];

function commandTable(): [name: string, desc: string, flags: string[]][] {
  const verbs: [string, string, string[]][] = REGISTRY.map((d) => [
    d.name,
    d.description.split(/\.(?=\s+[A-Z]|$)/)[0] ?? d.name,
    [...Object.keys(d.schema).map((k) => `--${k}`), ...VERB_FLAGS],
  ]);
  return [...STATIC_COMMANDS, ...verbs];
}

// Completion descriptions ride inside single-quoted shell strings — strip the
// characters each shell treats specially rather than escaping per-dialect.
const sanitize = (s: string) =>
  s
    .replace(/['":\\[\]`$]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 72);

function zsh(): string {
  const table = commandTable();
  const commands = table.map(([name, desc]) => `    '${name}:${sanitize(desc)}'`).join('\n');
  const cases = table
    .filter(([, , flags]) => flags.length > 0)
    .map(([name, , flags]) => `    ${name}) _arguments ${flags.map((f) => `'${f}'`).join(' ')} ;;`)
    .join('\n');
  return `#compdef phone-use
# Generated by \`phone-use completion zsh\`.
_phone_use() {
  local -a _pu_commands
  _pu_commands=(
${commands}
  )
  if (( CURRENT == 2 )); then
    _describe 'command' _pu_commands
    return
  fi
  case $words[2] in
${cases}
  esac
}
_phone_use "$@"
`;
}

function bash(): string {
  const table = commandTable();
  const names = table.map(([name]) => name).join(' ');
  const cases = table
    .filter(([, , flags]) => flags.length > 0)
    .map(([name, , flags]) => `    ${name}) COMPREPLY=($(compgen -W "${flags.join(' ')}" -- "$cur")) ;;`)
    .join('\n');
  return `# Generated by \`phone-use completion bash\`.
_phone_use() {
  local cur=\${COMP_WORDS[COMP_CWORD]}
  if [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=($(compgen -W "${names}" -- "$cur"))
    return
  fi
  case \${COMP_WORDS[1]} in
${cases}
  esac
}
complete -F _phone_use phone-use
`;
}

function fish(): string {
  const table = commandTable();
  const subcommands = table.map(([name]) => name).join(' ');
  const lines = table.flatMap(([name, desc, flags]) => [
    `complete -c phone-use -f -n "not __fish_seen_subcommand_from ${subcommands}" -a ${name} -d '${sanitize(desc)}'`,
    ...flags.map((f) => `complete -c phone-use -n "__fish_seen_subcommand_from ${name}" -l ${f.slice(2)}`),
  ]);
  return `# Generated by \`phone-use completion fish\`.\n${lines.join('\n')}\n`;
}

/** The completion script for one shell, or null for an unknown shell name. */
export function completionScript(shell: string): string | null {
  switch (shell) {
    case 'zsh':
      return zsh();
    case 'bash':
      return bash();
    case 'fish':
      return fish();
    default:
      return null;
  }
}
